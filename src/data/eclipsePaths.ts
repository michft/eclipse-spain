import type { GeoPoint } from "../domain/geo";

export interface TimedGeoPoint extends GeoPoint {
  timeUtc: string | null;
}

export interface EclipsePathGeometry {
  centerLine: readonly TimedGeoPoint[];
  northernLimit: readonly GeoPoint[];
  southernLimit: readonly GeoPoint[];
  totalityArea: readonly GeoPoint[];
}

type RawPathRow = readonly [
  timeUtc: string | null,
  northernLatitude: number | null,
  northernLongitude: number | null,
  southernLatitude: number | null,
  southernLongitude: number | null,
  centerLatitude: number | null,
  centerLongitude: number | null,
];

const point = (
  latitude: number | null,
  longitude: number | null,
): GeoPoint | null =>
  latitude === null || longitude === null ? null : { latitude, longitude };

const makePath = (rows: readonly RawPathRow[]): EclipsePathGeometry => {
  const northernLimit = rows.flatMap((row) => {
    const value = point(row[1], row[2]);
    return value ? [value] : [];
  });
  const southernLimit = rows.flatMap((row) => {
    const value = point(row[3], row[4]);
    return value ? [value] : [];
  });
  const centerLine = rows.flatMap((row) => {
    const value = point(row[5], row[6]);
    return value ? [{ ...value, timeUtc: row[0] }] : [];
  });
  return {
    centerLine,
    northernLimit,
    southernLimit,
    totalityArea: [...northernLimit, ...southernLimit.toReversed()],
  };
};

